class AppRuleRow(Adw.ActionRow):
    def __init__(self, app_info: dict, saved_settings: dict,
                 workspace_options: list[tuple[str, str]], on_change_cb):
        super().__init__()
        self._wm_class    = app_info["wm_class"]
        self._is_web_app  = app_info.get("is_web_app", False)
        self._cb          = on_change_cb


        self.set_title(app_info["name"])
        sub = app_info["wm_class"] or t("Unknown class")
        if self._is_web_app: sub += "  •  Web app"
        self.set_subtitle(sub)

        # Icon
        icon = Gtk.Image(); icon.set_pixel_size(32)
        icon_name = app_info.get("icon", "")
        theme = Gtk.IconTheme.get_for_display(icon.get_display()) if icon.get_display() else None
        if theme and icon_name and theme.has_icon(icon_name):
            icon.set_from_icon_name(icon_name)
        else:
            icon.set_from_icon_name("application-x-executable")
        icon.set_margin_end(8)
        self.add_prefix(icon)

        def _make_suffix(label_text, combo_options, saved_key, default_val):
            vbox = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=2)
            vbox.set_valign(Gtk.Align.CENTER)
            lbl = Gtk.Label(label=label_text)
            lbl.add_css_class("caption"); lbl.set_halign(Gtk.Align.START)
            vbox.append(lbl)
            combo = Gtk.ComboBoxText()
            for opt_id, opt_lbl in combo_options:
                combo.append(opt_id, opt_lbl)
            combo.set_active_id(saved_settings.get(saved_key, default_val))
            combo.connect("changed", lambda _: self._cb())
            vbox.append(combo)
            self.add_suffix(vbox)
            return combo

        default_match = "initial_title" if self._is_web_app else "class"
        self.match_combo = _make_suffix("Match",     MATCH_TYPE_OPTIONS, "match_type", default_match)
        self.ws_combo    = _make_suffix("Workspace", workspace_options,  "workspace",  "default")
        self.float_combo = _make_suffix(t("Behavior"), FLOAT_OPTIONS,      "float",      "default")

        # Ausgangszustand merken — zum Vergleich beim Speichern
        self._initial_state = {
            "match_type": self.match_combo.get_active_id() or "class",
            "workspace":  self.ws_combo.get_active_id()    or "default",
            "float":      self.float_combo.get_active_id() or "default",
        }

    def is_user_modified(self) -> bool:
        """True wenn der User mindestens einen Wert geändert hat."""
        current = {
            "match_type": self.match_combo.get_active_id() or "class",
            "workspace":  self.ws_combo.get_active_id()    or "default",
            "float":      self.float_combo.get_active_id() or "default",
        }
        return current != self._initial_state

