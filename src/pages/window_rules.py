class WindowRulesPage(Gtk.Box):
    def __init__(self, main_window, **kwargs):
        super().__init__(**kwargs)
        self.main_window = main_window
        self.set_orientation(Gtk.Orientation.VERTICAL)

        self._provider_banner = Adw.Banner()
        self._provider_banner.set_title(t("Choose a Hyprland configuration provider to unlock this page."))
        self.append(self._provider_banner)

        provider = load_provider()
        self._workspace_options, self.saved_rules, self._existing_rules = _load_provider_page_state(provider)
        self._imported_keys = _merge_imported_rules(self.saved_rules, self._existing_rules)
        self._rows: dict[str, "AppRuleRow"] = {}
        self._conflicts: list[str] = []
        self._scan_started = False
        self._provider_banner.set_revealed(provider is None)

        # Notebook mit zwei Tabs
        notebook = Gtk.Notebook()
        notebook.set_vexpand(True)
        self.append(notebook)
        notebook.append_page(self._build_app_tab(),      Gtk.Label(label=t("App rules")))
        notebook.append_page(self._build_existing_tab(), Gtk.Label(label=t("Existing rules")))

    # ── Tab 1 ─────────────────────────────────────────────────────────────────

    def _build_app_tab(self) -> Gtk.Widget:
        box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL)

        # Toolbar
        bar = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=8)
        bar.set_margin_top(12); bar.set_margin_bottom(8)
        bar.set_margin_start(12); bar.set_margin_end(12)
        self.search_entry = Gtk.SearchEntry()
        self.search_entry.set_hexpand(True)
        self.search_entry.set_placeholder_text(t("Search app..."))
        self.search_entry.connect("search-changed", self._on_search_changed)
        bar.append(self.search_entry)
        self._save_btn = Gtk.Button(label=t("Save & Apply"))
        self._save_btn.add_css_class("suggested-action")
        self._save_btn.connect("clicked", self._on_save_clicked)
        self._save_btn.set_sensitive(load_provider() is not None)
        bar.append(self._save_btn)
        box.append(bar)

        # Konflikt-Banner
        self.conflict_banner = Adw.Banner()
        self.conflict_banner.set_title(t("Conflicts detected"))
        self.conflict_banner.set_button_label(t("Details"))
        self.conflict_banner.connect("button-clicked", self._show_conflict_dialog)
        self.conflict_banner.set_revealed(False)
        box.append(self.conflict_banner)

        # Scroll + Liste
        scroller = Gtk.ScrolledWindow()
        scroller.set_vexpand(True)
        scroller.set_policy(Gtk.PolicyType.NEVER, Gtk.PolicyType.AUTOMATIC)
        self.pref_group = Adw.PreferencesGroup()
        self.pref_group.set_margin_top(4); self.pref_group.set_margin_bottom(12)
        self.pref_group.set_margin_start(12); self.pref_group.set_margin_end(12)
        scroller.set_child(self.pref_group)
        box.append(scroller)

        self.spinner = Gtk.Spinner()
        self.spinner.set_halign(Gtk.Align.CENTER)
        self.spinner.set_size_request(-1, 48)
        box.append(self.spinner)
        if load_provider() is not None:
            self._start_app_scan()
        else:
            self.spinner.set_visible(False)
        return box

    def _start_app_scan(self):
        if self._scan_started:
            return
        self._scan_started = True
        self.spinner.set_visible(True)
        self.spinner.start()
        threading.Thread(
            target=lambda: GLib.idle_add(self._populate_list, _scan_desktop_files()),
            daemon=True,
        ).start()

    def _populate_list(self, apps: list[dict]):
        self.spinner.stop()
        self.spinner.set_visible(False)
        for app in apps:
            saved = self.saved_rules.get(app["wm_class"], {})
            row = AppRuleRow(app, saved, self._workspace_options, self._on_rule_changed)
            self._rows[app["name"]] = row
            self.pref_group.add(row)

    def _on_search_changed(self, entry):
        q = entry.get_text().lower()
        for name, row in self._rows.items():
            row.set_visible(q in name.lower())

    def _on_rule_changed(self):
        # Konflikterkennung: selbe wm_class → zwei verschiedene Workspaces
        rules = []
        for row in self._rows.values():
            wm, s = row.get_rule()
            ws = s.get("workspace", "default")
            rules.append((wm, ws))

        conflicts = [
            f"• {c.wm_class}: {c.first_workspace} ↔ {c.conflicting_workspace}"
            for c in caelestia_core.find_conflicts(rules)
        ]
        self._conflicts = conflicts
        if conflicts:
            self.conflict_banner.set_title(f"{len(conflicts)} {t('conflicts detected')}")
            self.conflict_banner.set_revealed(True)
        else:
            self.conflict_banner.set_revealed(False)

    def _show_conflict_dialog(self, *_):
        dialog = Adw.MessageDialog(heading="Konflikte", body="\n".join(self._conflicts) or "–")
        dialog.add_response("ok", "OK")
        dialog.set_transient_for(self.main_window)
        dialog.present()

    def _on_save_clicked(self, btn):
        if self._conflicts:
            self._show_conflict_dialog()
            return

        # Button während des Speicherns deaktivieren → verhindert Doppelklick
        btn.set_sensitive(False)
        btn.set_label(t("Saving..."))

        # Welche wm_classes haben bereits manuelle (nicht-managed) Regeln?
        manual_classes: set[str] = set()
        for entry in self._existing_rules:
            if not entry["managed"]:
                for cls in entry["match_val"].split("|"):
                    cls = cls.strip().lstrip("^(").rstrip(")$")
                    if cls:
                        manual_classes.add(cls)

        rules = {}
        for row in self._rows.values():
            key, settings = row.get_rule()
            ws     = settings.get("workspace", "default")
            float_ = settings.get("float",     "default")
            if ws == "default" and float_ == "default":
                continue
            # Klassen mit manueller Regel nur schreiben wenn User sie geändert hat
            if key in manual_classes and not row.is_user_modified():
                continue
            rules[key] = settings

        # Providerabhängig in die echte Hyprland-Konfiguration schreiben und
        # live anwenden, BEVOR der lokale JSON-Cache aktualisiert wird — so
        # kann der Cache nie einen Stand enthalten, der beim sicheren
        # Config-Schreiben (Lua: luac-Validierung) oder beim Reload
        # tatsächlich verworfen wurde.
        provider = load_provider()
        if provider is None:
            self.main_window.add_toast(
                Adw.Toast.new(t("Choose a Hyprland configuration provider first."))
            )
            btn.set_sensitive(True)
            btn.set_label(t("Save & Apply"))
            return
        try:
            if provider is Provider.LUA:
                _save_window_rules_lua_and_reload(rules)
            else:
                _write_rules_conf(_generate_rules_lines(rules))
        except Exception as e:
            self.main_window.add_toast(Adw.Toast.new(f"{t('Error:')} {e}"))
            btn.set_sensitive(True)
            btn.set_label(t("Save & Apply"))
            return

        save_window_rules_config(rules)
        self.main_window.add_toast(Adw.Toast.new(t("Rules saved and Hyprland reloaded.")))
        self._existing_rules = _load_existing_rules()
        self._refresh_existing_tab()
        btn.set_sensitive(True)
        btn.set_label(t("Save & Apply"))

    # ── Tab 2 ─────────────────────────────────────────────────────────────────

    def _build_existing_tab(self) -> Gtk.Widget:
        box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL)
        self._existing_desc_label = Gtk.Label()
        self._existing_desc_label.set_margin_top(10)
        self._existing_desc_label.set_margin_bottom(6)
        self._existing_desc_label.set_margin_start(12)
        self._existing_desc_label.set_halign(Gtk.Align.START)
        box.append(self._existing_desc_label)

        scroller = Gtk.ScrolledWindow()
        scroller.set_vexpand(True)
        scroller.set_policy(Gtk.PolicyType.NEVER, Gtk.PolicyType.AUTOMATIC)
        self._existing_group = Adw.PreferencesGroup()
        self._existing_group.set_margin_top(4); self._existing_group.set_margin_bottom(12)
        self._existing_group.set_margin_start(12); self._existing_group.set_margin_end(12)
        scroller.set_child(self._existing_group)
        box.append(scroller)
        self._refresh_existing_tab()
        return box

    def _refresh_existing_tab(self):
        provider = load_provider()
        if provider is None:
            rules_path = ""
            desc = t("Choose Yes or No in the provider dialog before reading configuration.")
        else:
            rules_path = resolve_path("rules", provider)
            desc = (
                t("All hl.window_rule(...) entries from {path}  –  🔒 manual  /  ⚙ managed by this app")
                if provider is Provider.LUA
                else t("All windowrule entries from {path}  –  🔒 manual  /  ⚙ managed by this app")
            ).format(path=rules_path)
        self._existing_desc_label.set_markup(f"<small>{GLib.markup_escape_text(desc)}</small>")

        # AdwPreferencesGroup erlaubt kein remove() auf seine Rows —
        # stattdessen die Group komplett ersetzen.
        parent = self._existing_group.get_parent()   # ScrolledWindow
        new_group = Adw.PreferencesGroup()
        new_group.set_margin_top(4); new_group.set_margin_bottom(12)
        new_group.set_margin_start(12); new_group.set_margin_end(12)

        if not self._existing_rules:
            new_group.add(Adw.ActionRow(
                title=(
                    t("Hyprland configuration provider required")
                    if provider is None
                    else t("No windowrule entries found.")
                ),
                subtitle=(
                    t("Choose Yes or No in the provider dialog before editing configuration.")
                    if provider is None
                    else str(rules_path)
                ),
            ))
        else:
            for entry in self._existing_rules:
                icon = "⚙" if entry["managed"] else "🔒"
                row  = Adw.ActionRow()
                row.set_title(f"{icon}  {entry['rule']}")
                row.set_subtitle(
                    f"match:{entry['match_type']} {entry['match_val']}"
                    if entry["match_type"] else entry["raw"]
                )
                new_group.add(row)

        if parent:
            parent.set_child(new_group)
        self._existing_group = new_group

    def on_provider_changed(self):
        provider = load_provider()
        self._provider_banner.set_revealed(provider is None)
        self._save_btn.set_sensitive(provider is not None)
        if provider is None:
            return
        self._workspace_options, self.saved_rules, self._existing_rules = _load_provider_page_state(provider)
        self._imported_keys = _merge_imported_rules(self.saved_rules, self._existing_rules)
        self._refresh_existing_tab()
        self._start_app_scan()


